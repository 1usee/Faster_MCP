"""本服务的异常类型。

为什么要专门定义异常，而不是到处 raise ValueError？
因为 MCP 工具抛出异常时，客户端/模型看到的是错误文本。分层异常让我们能区分
"模型传错了参数"（可自愈，模型改一下再试）和"服务内部出错了"（模型重试也没用），
便于在 server 层统一转换成对模型友好、可读的提示。
"""

from __future__ import annotations


class FasterMcpError(Exception):
    """本项目所有异常的基类。捕获这个就等于捕获我们自己抛的全部错误。"""


class ToolInputError(FasterMcpError):
    """模型传入的参数不合法。

    对应"可自愈"类错误：表达式语法错误、任务名不存在、单位不匹配等。
    抛出这类异常时，错误信息应当写清楚"哪里错了、正确姿势是什么"，
    因为这句话会直接进模型的上下文，影响它下一次调用。
    """


class ToolExecutionError(FasterMcpError):
    """工具执行过程中失败，且不是调用方参数的问题。

    例如内部计算溢出、依赖缺失、上游服务不可用。模型重试通常无效。
    """


class FeatureLoadError(FasterMcpError):
    """功能模块加载失败：入口缺失、依赖成环、名称冲突等。

    这类错误发生在**启动阶段**，属于开发者错误而非运行时错误，
    因此 loader 会尽快抛出，让问题在自检时就暴露，而不是等模型调用才发现。
    """


class ResourceLimitError(ToolInputError):
    """输入合法但超出资源限额（表达式过长、幂指数过大等）。

    单独成类的原因：它是防御性拒绝，而非纯粹的语法错误。
    将来若要给限额做动态配置或分级限流，从这里切入最自然。
    """
